    private void AddBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_AddBtnMouseClicked
          if(ProdId.getText().isEmpty()|| ProdName.getText().isEmpty()||ProdPrice.getText().isEmpty()||ProdPrice.getText().isEmpty()||ProdQty.getText().isEmpty())
        {
             JOptionPane.showMessageDialog(this, "Missing Information");
        }
        else{
        try {
   Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/supermarketdb","root","new123");
   PreparedStatement add = Con.prepareStatement("insert into PRODUCTTBL values(?,?,?,?,?)");
            add.setInt(1, Integer.valueOf(ProdId.getText()));
            add.setString(2,ProdName.getText());
            add.setInt(3, Integer.valueOf(ProdQty.getText()));
            add.setInt(4, Integer.valueOf(ProdPrice.getText()));
            add.setString(5,CatCb.getSelectedItem().toString());
            JOptionPane.showMessageDialog(this, "Product Added Succesfully");
            int row = add.executeUpdate();
            Con.close();
            SelectSeller();
           
        }catch (Exception e){
            e.printStackTrace();
        } 
        }
    }//GEN-LAST:event_AddBtnMouseClicked

